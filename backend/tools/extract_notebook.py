LIMITS = {177:24,220:2,223:7,225:2,226:2,238:9,292:2}


def selected(index, node, position):
    if index == 13:
        return isinstance(node, ast.FunctionDef) and node.name == 'bits_to_bytes'
    if index == 246:
        return isinstance(node, ast.FunctionDef) and node.name == 'phase3j_derive_pair_seed'
    if position >= LIMITS.get(index, 10**6):
        return False
    if index == 177 and isinstance(node, (ast.Import, ast.ImportFrom)):
        return False
    if isinstance(node, (ast.Import, ast.ImportFrom, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        # Test-only deliberately failing model has no place in the deployed engine.
        return getattr(node, 'name', '') != 'VerificationAlwaysFailSwapModel'
    if isinstance(node, ast.Assert):
        return False  # Top-level notebook checks; checks INSIDE protocol functions stay.
    if isinstance(node, ast.Expr):
        return not (isinstance(node.value, (ast.Constant,)) or
                    isinstance(node.value, ast.Call) and isinstance(node.value.func, ast.Name)
                    and node.value.func.id in {'print', 'display'})
    if index == 177:
        return isinstance(node, ast.Assign) and all(isinstance(t, ast.Name) and t.id.startswith('PHASE3G2_') for t in node.targets)
    if index == 386:
        return isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id in {'PHASE4_POLICY_C_QBER_LIMIT','PHASE4_POLICY_C_MIN_VISIBILITY'} for t in node.targets)
    if index == 265:
        return isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id in {
            'PHASE3K_FARM_DISTANCE_KM','PHASE3K_FARM_REPEATER_COUNT','PHASE3K_FARM_MODE_COUNT',
            'PHASE3K_FARM_Z_PROBABILITY','PHASE3K_FARM_MAX_SLOTS_PER_PAIR',
            'PHASE3K_FARM_EXACT_FIELDS','PHASE3K_FARM_FLOAT_FIELDS','PHASE3K_FARM_FLOAT_ABS_TOL'} for t in node.targets)
    if index == 388 and isinstance(node, ast.For):
        return False  # Deployment validates prerequisites explicitly after model import.
    return True


def extract(notebook=ROOT / 'NARAD_QC.ipynb'):
    raw = notebook.read_bytes()
    doc = json.loads(raw)
    out = ROOT / 'backend/narad_backend'
    manifest = {'notebook_sha256': hashlib.sha256(raw).hexdigest(), 'cells': []}
    for filename, indices in [('engine.py',CORE), ('transport.py',TRANSPORT), ('farm.py',BENCHMARK), ('fitting.py',FIT)]:
        chunks = ['# Generated by backend/tools/extract_notebook.py; see source_manifest.json.\n']
        if filename == 'engine.py':
            chunks += ['from Crypto.Cipher import AES\nfrom Crypto.Random import get_random_bytes\n'
                       'import secrets\nimport time\nimport numpy as np\n'
                       'STANDARD_FIBER_ATTENUATION = 0.2\nNONCE_LEN = 12\n']
        for i in indices:
            source = ''.join(doc['cells'][i]['source'])
            tree = ast.parse(source)
            nodes = [a for j,a in enumerate(tree.body) if selected(i,a,j)]
            # Keep source text, decorators, comments inside definitions, and exact math.
            lines = source.splitlines()
            snippets=[]
            for a in nodes:
                start = min([a.lineno] + [d.lineno for d in getattr(a,'decorator_list',[])])-1
                snippets.append('\n'.join(lines[start:a.end_lineno]))
            chunks.append(f'\n# Notebook cell {i}: {source.splitlines()[0]}\n'+'\n\n'.join(snippets)+'\n')
            manifest['cells'].append({'index':i,'module':filename,'title':source.splitlines()[0], 'statements':len(nodes)})
        output='\n'.join(chunks)
        compile(output, filename, 'exec')
        (out/filename).write_text(output)
    (out/'source_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('Extracted runtime modules; notebook SHA256:',manifest['notebook_sha256'])

if __name__ == '__main__':
    extract()
